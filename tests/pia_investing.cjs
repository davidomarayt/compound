"use strict";
const assert=require("node:assert/strict");
const {estimate}=require("../compound/site/static/pia-investing.js");
const near=(a,b,msg)=>assert.ok(Math.abs(a-b)<.02,msg+": expected "+b+" got "+a);
const baseline={monthly:500,years:1,annual_return:0,pia_fee:0,etf_fee:0,shares_fee:0,etf_exit_rate:35,cgt_exemption:1270,dividend_yield:0,dividend_tax:40};
let a=estimate(baseline);
near(a.pia,6000,"PIA no growth");near(a.etf,6000,"ETF no growth");near(a.shares,6000,"Share no growth");
near(a.piaTaxes,0,"PIA no threshold");near(a.etfDeemedTaxes,0,"ETF short holding");near(a.sharesCGT,0,"Shares no gain");
assert.equal(a.contributed,6000);
a=estimate({...baseline,years:10,annual_return:6});
assert.ok(a.piaTaxes>0,"PIA daily average charge should arise");
assert.ok(a.etfDeemedTaxes>0,"8-year ETF deemed disposal is modelled per monthly lot");
assert.ok(a.etfFinalExitTax>0,"final ETF gain is taxed after deemed disposal");
assert.ok(a.sharesCGT>0,"shares incur CGT on disposal");
assert.ok(a.etf<a.etfHolding,"outside ETF after-tax must be below pre-sale value");
assert.ok(a.shares<a.sharesHolding,"shares after-tax must be below pre-sale value");
const ETF35=estimate({...baseline,years:10,annual_return:6,etf_exit_rate:35});
const ETF38=estimate({...baseline,years:10,annual_return:6,etf_exit_rate:38});
assert.ok(ETF35.etf>ETF38.etf,"lower future ETF rate must increase after-tax result");
const noDiv=estimate({...baseline,years:10,annual_return:6});
const withDiv=estimate({...baseline,years:10,annual_return:6,dividend_yield:3,dividend_tax:50});
assert.ok(withDiv.sharesDividendTaxes>0);
assert.ok(withDiv.shares<noDiv.shares,"personal dividend tax reduces investment compounding");
const noFees=estimate({...baseline,years:10,annual_return:6});
const fees=estimate({...baseline,years:10,annual_return:6,pia_fee:1,etf_fee:1,shares_fee:1});
assert.ok(fees.pia<noFees.pia && fees.etf<noFees.etf && fees.shares<noFees.shares);
const exempt=estimate({...baseline,years:5,annual_return:5,cgt_exemption:1270});
const notExempt=estimate({...baseline,years:5,annual_return:5,cgt_exemption:0});
assert.ok(exempt.shares>notExempt.shares);
const noGrowth=estimate({...baseline,years:30,annual_return:0});
near(noGrowth.etf,180000,"no growth 30 years ETF");
near(noGrowth.shares,180000,"no growth 30 years shares");
assert.ok(noGrowth.pia<180000,"PIA account tax can apply to contributions alone above 50k");
assert.equal(estimate({...baseline,monthly:2000}).monthly,1000,"PIA max contribution clamp");
console.log("PIA vs ETF/shares tax modelling tests passed");
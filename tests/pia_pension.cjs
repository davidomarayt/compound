/* Node arithmetic regression checks for the no-dependency PIA/pension comparison. */
"use strict";
const assert=require("node:assert/strict");
const {calculate}=require("../compound/site/static/pia-pension.js");
const base={monthly_net:500,years:1,current_age:35,relief_rate:0,relief_headroom:0,extra_employer:0,return_rate:0,pia_fee:0,pension_fee:0,tax_free_lump_pct:0,tax_free_cap:0,retirement_tax_rate:0};
const near=(actual,expected,msg)=>assert.ok(Math.abs(actual-expected)<.011,(msg||"")+" expected "+expected+" got "+actual);
let r=calculate(base);
near(r.pia,6000,"one-year PIA contribution");
near(r.pension,6000,"one-year pension no relief");
near(r.illustrativeNetPension,6000);
near(r.totalPiaTax,0);
r=calculate({...base,relief_rate:40,relief_headroom:10000});
near(r.pensionEmployeeYear,10000,"full relief at 40%");
near(r.reliefValue,4000);
near(r.pension,10000);
r=calculate({...base,relief_rate:40,relief_headroom:5000});
near(r.pensionEmployeeYear,8000,"headroom-capped pension contribution");
near(r.reliefValue,2000);
near(r.pensionEmployeeYear-r.reliefValue,6000,"same take-home budget");
r=calculate({...base,relief_rate:20,relief_headroom:100000,extra_employer:100});
near(r.pensionEmployeeYear,7500);
near(r.pension,8700,"pension includes 1200 incremental employer");
r=calculate({...base,years:10,monthly_net:1000});
near(r.totalPersonal,120000);
assert.ok(r.totalPiaTax>0,"PIA charge accrues after the daily average crosses 50k");
near(r.pension,120000);
r=calculate({...base,years:10,monthly_net:1000,return_rate:6,pia_fee:0.5,pension_fee:0.5});
const feeModel=r.pia;
const grossModel=calculate({...base,years:10,monthly_net:1000,return_rate:6,pia_fee:0,pension_fee:0});
assert.ok(grossModel.pia>feeModel,"fees lower PIA balances");
const taxable=calculate({...base,years:1,monthly_net:500,relief_rate:40,relief_headroom:10000,tax_free_lump_pct:25,tax_free_cap:200000,retirement_tax_rate:20});
near(taxable.illustrativeNetPension,8500,"25pct exempt and 20pct on remainder");
const capped=calculate({...base,years:30,monthly_net:1000,relief_rate:40,relief_headroom:100000,return_rate:6,tax_free_lump_pct:25,tax_free_cap:10000,retirement_tax_rate:40});
assert.ok(capped.freeLump<=10000,"lifetime free cap enforced");
assert.ok(capped.illustrativeNetPension<capped.pension,"pension net less than gross");
assert.equal(calculate({...base,current_age:35,years:10}).pensionAccessWarning,true);
console.log("PIA vs pension arithmetic checks passed"); 


/* Keep search-readable static examples identical to the interactive calculator model. */
const fs=require("node:fs");
const {renderTable,assumptions}=require("../scripts/pia_pension_static_examples.cjs");
const markdown=fs.readFileSync(require("node:path").join(__dirname,"../content/pages/pia-vs-pension.md"),"utf8");
const match=markdown.match(/<!-- pia-pension-examples:start -->([\s\S]*?)<!-- pia-pension-examples:end -->/);
assert.ok(match,"Public static comparison table missing");
assert.equal(match[1].trim(),renderTable().trim(),"Static table must match the calculator exactly");
assert.equal(assumptions.years,30);
assert.equal(assumptions.relief_headroom,23000);
const example=calculate({...assumptions,monthly_net:500,relief_rate:40,extra_employer:0});
assert.equal(Math.round(example.pia),412420,"30-year original PIA example");
assert.equal(Math.round(example.illustrativeNetPension),598914,"30-year original after-deductions pension example");
assert.ok(example.illustrativeNetPension<example.pension,"Illustrative pension net below gross");

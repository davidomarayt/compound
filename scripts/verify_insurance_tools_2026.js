"use strict";
const fs=require("node:fs");
const vm=require("node:vm");
const assert=require("node:assert/strict");
const code=fs.readFileSync(process.argv[2]||"compound/site/static/insurance-tools-2026.js","utf8");
const win={};
vm.runInNewContext(code,{window:win,document:{querySelectorAll(){return [];}},Intl,Number,Math}, {timeout:1500});
const compute=win.CompoundInsuranceMath.calculate;
assert.equal(typeof compute,"function");
const health=compute("health",{ap:1600,bp:1400,visits:1,outpatient:500,ae:125,be:250,as:0,bs:0,ar:230,br:180});
assert.equal(health.a,1995);assert.equal(health.b,1970);assert.equal(health.diff,25);assert.equal(health.winner,"Plan B");
const capped=compute("health",{ap:100,bp:100,visits:0,outpatient:20,ae:0,be:0,as:0,bs:0,ar:999,br:0});
assert.equal(capped.a,100,"reimbursement cannot exceed spending");
const home=compute("home",{area:145,rate:2400,extras:10,demolition:25000,outbuildings:5000,current:320000});
assert.equal(home.base,348000);assert.equal(home.extras,34800);assert.equal(home.total,412800);assert.equal(home.gap,92800);
const overinsured=compute("home",{area:100,rate:2000,extras:0,demolition:0,outbuildings:0,current:400000});assert.equal(overinsured.gap,0);assert.equal(overinsured.percent,200,"coverage ratio must not be visually capped");
const critical=compute("critical",{once:10000,monthly:1800,months:12,care:12000,debt:10000,savings:15000,existing:0});
assert.equal(critical.gross,53600);assert.equal(critical.gap,38600);
const criticalCovered=compute("critical",{once:0,monthly:100,months:6,care:0,debt:0,savings:10000,existing:0});assert.equal(criticalCovered.gap,0);
const death=compute("death",{salary:60000,multiple:4,monthly:2500,years:15,debt:20000,oneoff:10000,savings:50000,other:0});
assert.equal(death.dis,240000);assert.equal(death.target,480000);assert.equal(death.gap,190000);
const savings=compute("savings",{homecur:480,homenew:415,carcur:700,carnew:630,healthcur:1600,healthnew:1530,lifecur:360,lifenew:330,years:3,fees:60});
assert.equal(savings.current,3140);assert.equal(savings.new,2905);assert.equal(savings.annual,235);assert.equal(savings.horizon,645);
const worse=compute("savings",{homecur:10,homenew:20,carcur:0,carnew:0,healthcur:0,healthnew:0,lifecur:0,lifenew:0,years:5,fees:0});assert.equal(worse.annual,-10);assert.equal(worse.horizon,-50);
console.log("5 standalone insurance tools: 20 arithmetic and edge-case checks passed");
